"""Export chain logos from the fractal-ui sprite into nodeapi/assets/chains/<folder>.svg,
and generate chain-logos.css, which shows the logo before the page title on any page that
contains <span className="chain-logo-<folder>" /> (used on each chain's overview page).

Run from the repo root after the design team changes a logo, or after adding a chain to LOGOS:
    python3 scripts/export-chain-logos.py [path/to/fractal-ui/src/assets/sprite.svg]
"""
import os
import re
import sys

SPRITE = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser(
    '~/git/frontend/packages/fractal-ui/src/assets/sprite.svg')
OUT = 'nodeapi/assets/chains'

# docs folder under nodeapi/ -> sprite symbol id (same mapping as fractal-ui's ProtocolLogo)
LOGOS = {
    'aptos': 'apt', 'arbitrum': 'arb', 'arc': 'arc', 'avalanche': 'avax', 'base': 'base',
    'berachain': 'bera', 'bitcoin': 'btc', 'bsc': 'bnb', 'conflux': 'cfx', 'ethereum': 'eth',
    'hedera': 'hbar', 'hyperliquid': 'hype', 'icp': 'icp', 'mezo': 'mezo', 'monad': 'mon',
    'opbnb': 'opbnb', 'optimism': 'optimism', 'plasma': 'xpl', 'polygon': 'matic', 'rayls': 'rls',
    'robinhood-chain': 'rbh', 'solana': 'sol', 'somnia': 'stt', 'stellar': 'xlm', 'tempo': 'tempo',
    'tron': 'trx', 'unichain': 'uni', 'wemix': 'wemix', 'xrp-ledger-xrpl': 'xrp',
}

sprite = open(SPRITE).read()
os.makedirs(OUT, exist_ok=True)
for folder, sid in LOGOS.items():
    m = re.search(r'<symbol id="%s"([^>]*)>(.*?)</symbol>' % re.escape(sid), sprite, re.S)
    if not m:
        sys.exit('missing symbol %r for %s' % (sid, folder))
    view_box = re.search(r'viewBox="([^"]+)"', m.group(1)).group(1)
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s" width="40" height="40" fill="none">%s</svg>\n' % (
        view_box, m.group(2))
    open(os.path.join(OUT, folder + '.svg'), 'w').write(svg)

css = ['/* Generated by scripts/export-chain-logos.py. Do not edit by hand. */',
       '/* Chain logo before the page title (#page-title) on pages containing <span className="chain-logo-<folder>" /> */',
       '#content-area:has([class^="chain-logo-"]) #page-title { display: flex; align-items: center; gap: 0.75rem; }',
       '#content-area:has([class^="chain-logo-"]) #page-title::before {',
       '  content: ""; flex-shrink: 0; width: 2.25rem; height: 2.25rem;',
       '  background-position: center; background-repeat: no-repeat; background-size: contain;',
       '}']
css += ['#content-area:has(.chain-logo-%s) #page-title::before { background-image: url("/%s/%s.svg"); }'
        % (folder, OUT, folder) for folder in LOGOS]
css += ['/* Several logos are a white disc; outline them on the light theme so they keep their shape */',
        'html:not(.dark) img[src*="/%s/"],' % OUT,
        'html:not(.dark) #content-area:has([class^="chain-logo-"]) #page-title::before {',
        '  border-radius: 9999px; box-shadow: 0 0 0 1px rgb(0 0 0 / 0.12);',
        '}']
open('chain-logos.css', 'w').write('\n'.join(css) + '\n')
print('exported', len(LOGOS), 'logos to', OUT, 'and wrote chain-logos.css')
