"""Refresh nodeapi/openapi/stellar-wallet-backend.graphql from stellar/wallet-backend at a given commit or tag.

Merges the upstream schema files (internal/serve/graphql/schema/*.graphqls) into the one SDL file Mintlify reads
for the Stellar "Wallet Backend" reference, and drops @goField, a Go code-generation hint with no client meaning.
Use the commit Validation Cloud deploys:
    python3 scripts/update-wallet-backend-schema.py <commit-or-tag>
"""
import json
import re
import sys
import urllib.request

REPO = 'stellar/wallet-backend'
SCHEMA_DIR = 'internal/serve/graphql/schema'
OUT = 'nodeapi/openapi/stellar-wallet-backend.graphql'

if len(sys.argv) != 2:
    sys.exit(__doc__)
ref = sys.argv[1]
get = lambda url: urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'vc-docs'}), timeout=30).read().decode()

listing = json.loads(get('https://api.github.com/repos/%s/contents/%s?ref=%s' % (REPO, SCHEMA_DIR, ref)))
names = sorted(f['name'] for f in listing if f['name'].endswith('.graphqls'))
parts = []
for name in names:
    sdl = get('https://raw.githubusercontent.com/%s/%s/%s/%s' % (REPO, ref, SCHEMA_DIR, name))
    sdl = re.sub(r'(?:"""[^"]*"""\s*)?directive @goField\(.*?\) on [A-Z_| ]+\n', '', sdl, flags=re.S)
    sdl = re.sub(r'\s*@goField\([^)]*\)', '', sdl)
    parts.append('# ---- %s ----\n%s\n' % (name, sdl.strip()))

merged = '\n'.join(parts)
if '@goField' in merged or 'type Query' not in merged:
    sys.exit('unexpected schema shape; check the upstream files')
header = ('# Stellar wallet-backend GraphQL schema, merged from %s/%s at %s (Apache-2.0).\n'
          '# Generated by scripts/update-wallet-backend-schema.py. Do not edit by hand.\n\n' % (REPO, SCHEMA_DIR, ref))
open(OUT, 'w').write(header + merged)
print('wrote %s from %d files at %s' % (OUT, len(names), ref))
